// Prepares a Flatpak build folder from the Linux tar.gz that electron-builder made.
//
//   node scripts/flatpak.mjs local <tar.gz>            -> dist/flatpak/  (builds from the local tar.gz; CI's .flatpak bundle)
//   node scripts/flatpak.mjs flathub <tar.gz> <owner/repo> -> dist/flathub/ (downloads the GitHub release asset; the files
//                                                         to put in the github.com/flathub/ca.sayfern.Sayfern repo)
//
// Both copy flatpak/*, write the current version and its CHANGELOG date into the metainfo, and keep
// the manifest in flatpak/ as the single source.
import { createHash } from "node:crypto";
import { copyFileSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { basename, dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ID = "ca.sayfern.Sayfern";
const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const src = join(root, "flatpak");
const [mode, tarball, repo] = process.argv.slice(2);

const { version } = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));
const date = readFileSync(join(root, "CHANGELOG.md"), "utf8").match(new RegExp(`^## \\[${version.replaceAll(".", "\\.")}\\] - (\\S+)`, "m"))?.[1];
if (!date) throw new Error(`CHANGELOG.md has no "## [${version}] - <date>" heading.`);

const out = join(root, "dist", mode === "local" ? "flatpak" : "flathub");
rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });
for (const file of ["sayfern.sh", `${ID}.desktop`]) copyFileSync(join(src, file), join(out, file));

const metainfo = readFileSync(join(src, `${ID}.metainfo.xml`), "utf8").replace(
  /<releases>[\s\S]*?<\/releases>/,
  `<releases>\n    <release version="${version}" date="${date}">\n      <url type="details">https://github.com/${repo ?? "yufengliu15/Sayfern"}/releases/tag/v${version}</url>\n    </release>\n  </releases>`,
);
writeFileSync(join(out, `${ID}.metainfo.xml`), metainfo);

const LOCAL_SOURCE = "      - type: archive\n        path: sayfern-linux-x64.tar.gz\n        dest: sayfern\n";
let manifest = readFileSync(join(src, `${ID}.yml`), "utf8");
if (!manifest.includes(LOCAL_SOURCE)) throw new Error(`flatpak/${ID}.yml: the tar.gz source block changed; update scripts/flatpak.mjs.`);

if (mode === "local") {
  copyFileSync(tarball, join(out, "sayfern-linux-x64.tar.gz"));
} else {
  const asset = basename(tarball);
  const sha256 = createHash("sha256").update(readFileSync(tarball)).digest("hex");
  manifest = manifest.replace(
    LOCAL_SOURCE,
    [
      "      - type: archive",
      `        url: https://github.com/${repo}/releases/download/v${version}/${asset}`,
      `        sha256: ${sha256}`,
      "        dest: sayfern",
      // Flathub's external data checker opens a pull request when a newer release appears.
      "        x-checker-data:",
      "          type: json",
      `          url: https://api.github.com/repos/${repo}/releases/latest`,
      '          version-query: .tag_name | sub("^v"; "")',
      '          url-query: .assets[] | select(.name == "Sayfern-" + $version + "-linux-x64.tar.gz") | .browser_download_url',
      "",
    ].join("\n"),
  );
  // Only an x64 Linux build exists so far.
  writeFileSync(join(out, "flathub.json"), `${JSON.stringify({ "only-arches": ["x86_64"] }, null, 2)}\n`);
}
writeFileSync(join(out, `${ID}.yml`), manifest.replace(/^(#.*\n)+/, `# Generated by scripts/flatpak.mjs (${mode}) for Sayfern ${version}.\n`));
console.log(`[flatpak] ${out}`);
